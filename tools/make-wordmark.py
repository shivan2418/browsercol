#!/usr/bin/env python3
"""Draws BrowserCol's wordmark (#284): BROWSERCOL in Cinzel Bold with the two globes of the icon as the O's.

The letters are outlined from the bundled font, so the wordmark never waits for a font. The globes are
cut out of ui/brand/icon.svg: the Americas (the front globe) is the first O, Europe and Africa the second.
Writes ui/brand/wordmark.svg (self-contained, in the icon's ink), ui/brand/globe-americas.svg and
ui/brand/globe-oldworld.svg (the loading screen shows the letters in the page's text colour and the globes
as images), and .cache/wordmark-inline.svg-fragment, the markup index.html carries (pasted there by hand).

Needs fontTools and brotli, which are not in the dev image; run it in a throwaway container:
  docker run --rm -v "$PWD:/w" -w /w debian:stable-slim sh -c \
    'apt-get update -qq && apt-get install -y -qq python3-fonttools python3-brotli && python3 tools/make-wordmark.py'
"""
import os
import re
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

INK = '#3b2410'
TEXT = 'BROWSERCOL'
SPACING = 20  # letter-spacing, in font units (0.02em)
GLOBE_MARGIN = -24.5  # beside a globe, as in the prototype: -0.035 of the cap height
OVERSHOOT = 10.5  # a round letter dips a little below the baseline
RIM = 48  # the globe's outer radius in icon.svg's own units (radius 46 plus half the 4-wide rim)

font = TTFont('ui/src/fonts/cinzel/cinzel-latin-700-normal.woff2')
glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
cap = font['OS/2'].sCapHeight
d = cap * 1.03  # a globe is a little taller than a capital, as a round O is
k = d / (2 * RIM)  # the scale from icon units to wordmark units
cy = OVERSHOOT - d / 2

icon = open('ui/brand/icon.svg', encoding='utf8').read()
defs = re.search(r'<defs>(.*)</defs>', icon, re.S).group(1)
defs = re.sub(r'<clipPath id="gap">.*?</clipPath>', '', defs)
def part(prefix):
    return ''.join(re.findall(r'<(?:pattern|filter|clipPath) id="%s-.*?</(?:pattern|filter|clipPath)>' % prefix, defs, re.S))
old_g = re.search(r'<g transform="translate\([^)]*\)">(.*?)</g><circle cx="50" cy="50" r="48.6"', icon, re.S).group(1)
new_g = re.search(r'r="48.6"[^>]*/>(<g>.*</g>)</svg>', icon, re.S).group(1)
globes = [('americas', 'new', new_g), ('oldworld', 'old', '<g>' + old_g + '</g>')]

# Lay the letters out left to right; each O is a globe's slot.
x, path, slots, i = 0.0, [], [], 0
for ch in TEXT:
    if ch == 'O':
        x += GLOBE_MARGIN
        slots.append(x)
        x += d + GLOBE_MARGIN + SPACING
        continue
    g = glyphs[cmap[ord(ch)]]
    pen = SVGPathPen(glyphs, ntos=lambda v: ('%.1f' % v).rstrip('0').rstrip('.'))
    g.draw(TransformPen(pen, (1, 0, 0, -1, x, 0)))
    path.append(pen.getCommands())
    x += g.width + SPACING
width = x - SPACING
letters = ''.join(path)
pad = 24
view = f'{-pad:g} {-pad - d + OVERSHOOT:.1f} {width + 2 * pad:.1f} {d + 2 * pad:.1f}'

def globe_at(slot, prefix, body):
    return f'<g transform="translate({slot + d / 2 - 50 * k:.2f} {cy - 50 * k:.2f}) scale({k:.4f})">{body}</g>'

whole = ''.join(globe_at(s, p, b) for s, (_, p, b) in zip(slots, globes))
open('ui/brand/wordmark.svg', 'w', encoding='utf8').write(
    '<!-- BrowserCol\'s wordmark (#284): BROWSERCOL in Cinzel Bold, outlined, with the icon\'s two globes as the O\'s.\n'
    '     Generated by tools/make-wordmark.py from ui/brand/icon.svg; do not edit by hand. -->\n'
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}" role="img"><title>BrowserCol</title>'
    f'<defs>{part("new")}{part("old")}</defs><path d="{letters}" fill="{INK}"/>{whole}</svg>\n')
for name, prefix, body in globes:
    open(f'ui/brand/globe-{name}.svg', 'w', encoding='utf8').write(
        f'<!-- One globe of BrowserCol\'s icon, for the loading screen (#284). Generated by tools/make-wordmark.py. -->\n'
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><defs>{part(prefix)}</defs>{body}</svg>\n')
# What index.html carries: the letters in the page's text colour, the globes as images.
imgs = ''.join(
    f'<image href="/brand/globe-{n}.svg" x="{s:.1f}" y="{cy - d / 2:.1f}" width="{d:.1f}" height="{d:.1f}"/>'
    for s, (n, _, _) in zip(slots, globes))
os.makedirs('.cache', exist_ok=True)
open('.cache/wordmark-inline.svg-fragment', 'w', encoding='utf8').write(
    f'<svg viewBox="{view}" role="img" aria-label="BrowserCol"><path d="{letters}" fill="currentColor"/>{imgs}</svg>\n')
print(view, len(letters))
