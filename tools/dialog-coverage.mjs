#!/usr/bin/env node
// Which dialogs a real game in the browser has reached: the list of every dialog the game can ask, merged with
// the counts the browser scripts wrote (ui/scripts/common.ts, trackCoverage) into docs/parity/dialog-coverage.md.
//
// The list is
//   - each show* method WebGUI overrides (engine/.../WebGUI.java), counted there by WebGUI.count, and
//   - each panel the Browser UI shows by itself that Swing opens from its own UI (a useCoverage('showXxx') in
//     ui/src), named for the Swing GUI method it stands for, counted by ui/src/coverage.ts.
// Counting is on only when a script installs window.fcCoverageHit; it is off for a player.
//
// Usage: run the scripts (`just dialog-coverage-run`), then ./dev.sh node tools/dialog-coverage.mjs [countsDir] [outFile]
// (defaults: .cache/coverage, docs/parity/dialog-coverage.md).

import { readFileSync, readdirSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..');
const countsDir = join(repo, process.argv[2] ?? '.cache/coverage');
const outFile = join(repo, process.argv[3] ?? 'docs/parity/dialog-coverage.md');
const SCRIPTS = ['smoke', 'play', 'saves', 'europe', 'debug', 'tileset'];

const walk = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });

// The WebGUI's dialogs: the distinct show* methods it overrides.
const webGui = readFileSync(join(repo, 'engine/src/main/java/browsercol/web/WebGUI.java'), 'utf8');
const engineNames = [...new Set([...webGui.matchAll(/^ {4}(?:public|protected) [^=;]*?\b(show[A-Z]\w*)\(/gm)].map((m) => m[1]))].sort();

// The Browser UI's own panels.
const uiNames = [
  ...new Set(
    walk(join(repo, 'ui/src'))
      .filter((f) => /\.tsx?$/.test(f) && !/\.(test|stories)\./.test(f))
      .flatMap((f) => [...readFileSync(f, 'utf8').matchAll(/useCoverage\('(\w+)'\)|coverageHit\('(\w+)'\)/g)].map((m) => m[1] ?? m[2])),
  ),
].sort();

// How many places in Swing open each one, from the parity inventory.
const inventory = JSON.parse(readFileSync(join(repo, 'docs/parity/swing-inventory.json'), 'utf8'));
const swingSites = {};
for (const r of inventory.rows) if (r.kind === 'opens') swingSites[r.target.replace(/^GUI\./, '')] = (swingSites[r.target.replace(/^GUI\./, '')] ?? 0) + 1;

// The counts: <script>.json is { browser: { dialog: n } }; "ui:" names are the Browser UI's.
const found = {};
if (existsSync(countsDir)) {
  for (const f of readdirSync(countsDir).filter((f) => f.endsWith('.json')).sort()) {
    found[f.replace(/\.json$/, '')] = JSON.parse(readFileSync(join(countsDir, f), 'utf8'));
  }
}
const scripts = [...SCRIPTS, ...Object.keys(found).filter((s) => !SCRIPTS.includes(s))];
const countOf = (script, key) => Object.values(found[script] ?? {}).reduce((sum, c) => sum + (c[key] ?? 0), 0);
const browsersOf = (script) => Object.keys(found[script] ?? {}).sort().join(', ');

const rows = [
  ...engineNames.map((name) => ({ name, key: name, kind: 'WebGUI' })),
  ...uiNames.map((name) => ({ name, key: `ui:${name}`, kind: 'Browser UI' })),
].map((r) => {
  const per = scripts.map((s) => countOf(s, r.key));
  return { ...r, per, total: per.reduce((a, b) => a + b, 0), swing: swingSites[r.name] ?? 0 };
});
// Names a script counted that the list does not have: the list is out of date.
const known = new Set(rows.map((r) => r.key));
const strays = [...new Set(Object.values(found).flatMap((b) => Object.values(b).flatMap((c) => Object.keys(c))))].filter((k) => !known.has(k)).sort();

rows.sort((a, b) => (a.total === 0) - (b.total === 0) || (a.total === 0 ? a.name.localeCompare(b.name) : b.total - a.total || a.name.localeCompare(b.name)));
const never = rows.filter((r) => r.total === 0);

const out = [];
out.push('# Dialog coverage', '');
out.push('Generated by `tools/dialog-coverage.mjs` (`just dialog-coverage`) from the counts the browser scripts write; do not edit by hand.');
out.push('Each row is a dialog or question the game can ask. *WebGUI* rows are the `show*` methods `WebGUI` implements, counted where');
out.push('they run in a real game; *Browser UI* rows are panels the page shows by itself that Swing opens from its own UI, named for');
out.push('the Swing GUI method. Counts are summed over the browsers a script ran in. Counting is on only for the scripts: they install');
out.push('`window.fcCoverageHit`, and a page without it counts nothing. `dialogs.ts` is a helper the scripts share, not a script.', '');
out.push(`- ${rows.length} dialogs (${engineNames.length} WebGUI, ${uiNames.length} Browser UI); ${rows.length - never.length} reached, ${never.length} never reached`);
for (const s of scripts) {
  out.push(`- \`${s}\`: ${found[s] ? `ran in ${browsersOf(s)}` : 'no counts (not run)'}`);
}
out.push('', `## Never reached (${never.length})`, '');
for (const r of never) out.push(`- \`${r.name}\` (${r.kind}${r.swing ? `, Swing opens it from ${r.swing} place${r.swing > 1 ? 's' : ''}` : ''})`);
if (strays.length) out.push('', '## Counted but not in the list', '', ...strays.map((k) => `- \`${k}\``));
out.push('', '## All dialogs, never reached first', '');
out.push(`| Dialog | Kind | Swing sites | ${scripts.join(' | ')} | Total |`);
out.push(`|---|---|---:|${scripts.map(() => '---:').join('|')}|---:|`);
for (const r of rows) out.push(`| \`${r.name}\` | ${r.kind} | ${r.swing || ''} | ${r.per.map((n) => n || '').join(' | ')} | ${r.total} |`);
out.push('');
writeFileSync(outFile, out.join('\n'));
console.log(`${outFile}: ${rows.length} dialogs, ${never.length} never reached${strays.length ? `, ${strays.length} not in the list` : ''}`);
